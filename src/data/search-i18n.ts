/** The line around the bold query: "{before}“q”{after}" */
export function resultsLine(n: number, lang: Lang) {
  if (lang === "hi") return { before: "", after: ` के लिए ${n} परिणाम` };
  if (lang === "te") return { before: "", after: ` కోసం ${n} ఫలితాలు` };
  return { before: `${n} ${n === 1 ? "result" : "results"} for `, after: "" };
}

